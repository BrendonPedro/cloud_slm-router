"""Summarise results/stage0_raw.json into results/stage0_summary.md (mean ± std over seeds
for in-domain; per-fold for LODO). Pure formatting: no new numbers are computed except
means/stds of numbers already in the raw file."""
import collections, json, math, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
raw = json.load(open(os.path.join(HERE, "results", "stage0_raw.json")))["results"]
ROUTERS = ["always-edge", "always-cloud", "random", "dataset-prior", "tfidf-lr", "oracle"]
COLS = ["test_call_rate", "test_quality", "test_strong", "met", "random_same_rate_quality", "deferral_auc", "ece", "brier"]


def ms(xs):
    xs = [float(x) for x in xs if x is not None]
    if not xs:
        return "–"
    m = sum(xs) / len(xs)
    if len(xs) == 1:
        return f"{m:.3f}"
    sd = math.sqrt(sum((x - m) ** 2 for x in xs) / (len(xs) - 1))
    return f"{m:.3f} ± {sd:.3f}"


out = ["# Stage-0 results (auto-generated by summarize.py from stage0_raw.json; do not edit by hand)", ""]
groups = collections.defaultdict(list)
for r in raw:
    groups[(r["pair"], r["setting"])].append(r)
for (pair, setting) in sorted(groups):
    rs = groups[(pair, setting)]
    n = sorted({r["n_test"] for r in rs})
    seeds = sorted({r["seed"] for r in rs})
    out += [f"## {pair} — {setting}  (n_test={n}, seeds={seeds})", "",
            "| router | " + " | ".join(COLS) + " |", "|---|" + "---|" * len(COLS)]
    for name in ROUTERS:
        sel = [r for r in rs if r["router"] == name]
        cells = []
        for c in COLS:
            vals = [r.get(c) for r in sel]
            if c == "met":
                vals = [v for v in vals if v is not None]
                cells.append(f"{sum(bool(v) for v in vals)}/{len(vals)}" if vals else "–")
            else:
                cells.append(ms(vals))
        out.append(f"| {name} | " + " | ".join(cells) + " |")
    out += ["", "Paired bootstrap, deferral AUC (tfidf-lr minus baseline), 95% percentile CI per seed:", ""]
    for r in rs:
        if r["router"].startswith("bootstrap"):
            excl = "excludes 0" if (r["lo"] > 0 or r["hi"] < 0) else "includes 0"
            out.append(f"- seed {r['seed']}: {r['router'].split(': ')[1]}: {r['diff']:+.4f} [{r['lo']:+.4f}, {r['hi']:+.4f}] ({excl}; B={r['B']})")
    out.append("")
open(os.path.join(HERE, "results", "stage0_summary.md"), "w").write("\n".join(out) + "\n")
print("\n".join(out))
