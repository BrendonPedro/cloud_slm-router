"""Generate paper/tables/stage0_*.tex from experiments/prototype/results/stage0_raw.json.

Pure formatting: every number in the generated tables is either copied from the raw
file or is a mean/std over seeds of numbers in the raw file. Nothing is typed by hand.
Stdlib only. Usage: python3 paper/make_tables.py
"""
import collections, hashlib, json, math, os

HERE = os.path.dirname(os.path.abspath(__file__))
RAW = os.path.join(HERE, "..", "experiments", "prototype", "results", "stage0_raw.json")
OUT = os.path.join(HERE, "tables")
ROUTERS = ["always-edge", "always-cloud", "random", "dataset-prior", "tfidf-lr", "oracle"]
LABEL = {"always-edge": "Always-edge", "always-cloud": "Always-cloud", "random": "Random",
         "dataset-prior": "Dataset-prior$^\\dagger$", "tfidf-lr": "TF-IDF+LR", "oracle": "Oracle$^\\ddagger$"}
FOLDS = ["MMLU-Pro", "GPQA", "LiveCodeBench", "math"]


def ms(xs):
    xs = [float(x) for x in xs if x is not None]
    if not xs:
        return "--"
    m = sum(xs) / len(xs)
    if len(xs) == 1:
        return f"{m:.3f}"
    sd = math.sqrt(sum((x - m) ** 2 for x in xs) / (len(xs) - 1))
    return f"{m:.3f}$\\pm${sd:.3f}"


def met(xs):
    xs = [x for x in xs if x is not None]
    return f"{sum(bool(x) for x in xs)}/{len(xs)}" if xs else "--"


raw_bytes = open(RAW, "rb").read()
raw = json.loads(raw_bytes)["results"]
sha = hashlib.sha256(raw_bytes).hexdigest()
g = collections.defaultdict(list)
for r in raw:
    g[(r["pair"], r["setting"], r["router"])].append(r)
os.makedirs(OUT, exist_ok=True)
hdr = f"% AUTO-GENERATED by paper/make_tables.py from stage0_raw.json (sha256 {sha}). Do not edit.\n"

# Table: in-domain, both pairs, mean +- std over 5 seeds.
rows = []
for pair in ["P-L", "P-Q"]:
    rows.append(f"\\multicolumn{{6}}{{l}}{{\\textit{{Pair {pair}}}}} \\\\")
    for name in ROUTERS:
        rs = g[(pair, "in-domain", name)]
        rows.append(" & ".join([LABEL[name],
                                ms([r["test_call_rate"] for r in rs]),
                                ms([r["test_quality"] for r in rs]),
                                met([r.get("met") for r in rs]),
                                ms([r.get("deferral_auc") for r in rs]),
                                ms([r.get("ece") for r in rs])]) + " \\\\")
with open(os.path.join(OUT, "stage0_indomain.tex"), "w") as f:
    f.write(hdr)
    f.write("\\begin{tabular}{lccccc}\n\\hline\n")
    f.write("Router & Call rate & Quality & Target met & Deferral AUC & ECE \\\\\n\\hline\n")
    f.write("\n".join(rows) + "\n\\hline\n\\end{tabular}\n")

# Table: LODO deferral AUC per held-out group (single split, seed 0).
rows = []
for pair in ["P-L", "P-Q"]:
    for fold in FOLDS:
        cells = [pair, fold]
        for name in ["random", "dataset-prior", "tfidf-lr", "oracle"]:
            rs = g[(pair, f"LODO:{fold}", name)]
            cells.append(ms([r.get("deferral_auc") for r in rs]))
        rows.append(" & ".join(cells) + " \\\\")
with open(os.path.join(OUT, "stage0_lodo.tex"), "w") as f:
    f.write(hdr)
    f.write("\\begin{tabular}{llcccc}\n\\hline\n")
    f.write("Pair & Held-out & Random & Dataset-prior & TF-IDF+LR & Oracle \\\\\n\\hline\n")
    f.write("\n".join(rows) + "\n\\hline\n\\end{tabular}\n")
print("wrote", sorted(os.listdir(OUT)), "from raw sha256", sha)
